def seed_statutory_leads(session: Session, reset: bool = False) -> int:
    """
    Seeds verified statutory leads into database session.
    Idempotent: updates existing leads or inserts new ones.
    """
    now = datetime.now(timezone.utc)
    count = 0
    for lead_data in STATUTORY_CORPORATE_LEADS:
        lead_id = lead_data["lead_id"]
        lead = session.get(LeadModel, lead_id)
        if not lead:
            lead = LeadModel(
                **lead_data,
                verified_at=now,
                created_at=now,
                updated_at=now,
            )
            session.add(lead)
        else:
            for k, v in lead_data.items():
                setattr(lead, k, v)
            lead.verified_at = now
            lead.updated_at = now
        count += 1
    session.commit()
    return count


